# Crie um código onde o usuário deve inserir dois números e exiba a soma, subtração, multiplicação e divisão deles.
p_numero = int(input())
s_numero = int(input())
soma = p_numero + s_numero
subtracao = p_numero - s_numero
multiplicacao = p_numero * s_numero
divisao = p_numero / s_numero
print(f"A soma deles é: {soma}")
print(f"A subtração deles é: {subtracao}")
print(f"A multiplicação deles é: {multiplicacao}")
print(f"A divisão deles é: {divisao}")